package com.geo.enums;

/**
 * 【任务状态枚举】
 *
 * 设计思路：
 * 1. 为什么用枚举？
 *    - 限定状态的取值范围，防止随便写字符串出错
 *    - 枚举比字符串常量更安全，有编译器检查
 *    - 方便后续维护，所有状态集中管理
 *
 * 2. 状态流转说明（核心业务流程）：
 *    PENDING（待提交）→ 用户创建任务后还没点提交
 *    PROCESSING（处理中）→ 点击提交，RPA机器人正在跑任务
 *    PAUSED（已暂停）→ 用户手动暂停了任务
 *    COMPLETED（全部成功）→ 所有子任务都成功完成
 *    PARTIAL_FAILED（部分失败）→ 有成功也有失败
 *    FAILED（全部失败）→ 所有子任务都失败了
 *    CANCELLED（已取消）→ 用户手动终止了任务
 *
 * 3. 这种设计叫"状态机模式"，确保任务只能在正确的状态间流转
 */
public enum TaskStatus {
    // 待提交：刚创建，还没点击开始按钮
    PENDING,
    // 处理中：RPA机器人正在各个AI平台上跑问题
    PROCESSING,
    // 已暂停：用户点了暂停，已开始的会跑完，没开始的先不派
    PAUSED,
    // 全部成功：所有子任务（AI平台×问题数）都成功
    COMPLETED,
    // 部分失败：有成功也有失败
    PARTIAL_FAILED,
    // 全部失败：所有子任务都失败了
    FAILED,
    // 已取消：用户手动终止
    CANCELLED
}